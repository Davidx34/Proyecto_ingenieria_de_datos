-- Una linea con valor no puede valer mas que la venta completa.
create trigger trg_detalle_valor_coherente
before insert on DetalleVenta
for each row
begin
    declare v_total decimal(12,2);
    if new.valorLinea is not null then
        select valorTotal into v_total from Venta where idVenta = new.idVenta;
        if new.valorLinea > v_total then
            signal sqlstate '45000' set message_text = 'El valor de la linea supera el total de la venta';
        end if;
    end if;
end$$

-- Lo mismo al completar o corregir el valor de una linea ya existente.
create trigger trg_detalle_valor_coherente_upd
before update on DetalleVenta
for each row
begin
    declare v_total decimal(12,2);
    if new.valorLinea is not null then
        select valorTotal into v_total from Venta where idVenta = new.idVenta;
        if new.valorLinea > v_total then
            signal sqlstate '45000' set message_text = 'El valor de la linea supera el total de la venta';
        end if;
    end if;
end$$

-- Bitacora: todo cambio o borrado de una venta o un gasto deja rastro.
create trigger trg_venta_bitacora_modifica
after update on Venta
for each row
begin
    insert into BitacoraCambio (fechaCambio, usuarioBD, tablaAfectada, idRegistro, accion, valorAnterior, valorNuevo)
    values (now(), user(), 'Venta', old.idVenta, 'MODIFICA',
            concat('fecha=', old.fechaVenta, '; cliente=', old.idCliente, '; total=', old.valorTotal, '; pago=', old.idMetodoPago),
            concat('fecha=', new.fechaVenta, '; cliente=', new.idCliente, '; total=', new.valorTotal, '; pago=', new.idMetodoPago));
end$$

