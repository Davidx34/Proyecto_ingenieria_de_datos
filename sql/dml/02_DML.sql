-- Tres intentos fallidos bloquean la cuenta de forma automatica.
create trigger trg_usuario_bloqueo_automatico
before update on Usuario
for each row
begin
    if new.intentosFallidos >= 3 then
        set new.bloqueado = 1;
    end if;
